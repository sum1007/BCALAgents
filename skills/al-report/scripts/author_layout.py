#!/usr/bin/env python3
"""
BC Report Layout Automation Script (for @bc-report-layout)
Safely populates compiler-generated Business Central .docx and .rdl/.rdlc layouts
by reading the embedded Custom XML dataset (or RDL <DataSets>) without ever
modifying or corrupting the Business Central schema elements.
"""

import argparse
import os
import re
import shutil
import tempfile
import xml.etree.ElementTree as ET
import zipfile


def humanize(name: str) -> str:
    s = re.sub(r'(Lbl|Caption|Formatted|LCY)$', '', name)
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1 \2', s)
    return s.strip() or name


def is_numeric_name(name: str) -> bool:
    low = name.lower()
    return any(k in low for k in ('amount', 'amt', 'qty', 'quantity', 'price', 'total', 'balance', 'cost', 'sales', 'vat', 'tax'))


def make_sdt_text(alias: str, xpath: str, ns_uri: str, store_id: str, placeholder: str, bold: bool = False, align: str = 'left', font_size_half_pt: int = 20, color: str = None) -> str:
    jc = f'<w:jc w:val="{align}"/>' if align != 'left' else ''
    b_tag = '<w:b/><w:bCs/>' if bold else ''
    c_tag = f'<w:color w:val="{color}"/>' if color else ''
    return f"""<w:sdt>
      <w:sdtPr>
        <w:rPr>{b_tag}{c_tag}<w:sz w:val="{font_size_half_pt}"/><w:szCs w:val="{font_size_half_pt}"/></w:rPr>
        <w:alias w:val="{alias}"/>
        <w:tag w:val="{alias}"/>
        <w:dataBinding w:prefixMappings="xmlns:ns0='{ns_uri}'" w:xpath="{xpath}" w:storeItemID="{store_id}"/>
        <w:text/>
      </w:sdtPr>
      <w:sdtContent>
        <w:p>
          <w:pPr>{jc}<w:spacing w:before="40" w:after="40"/></w:pPr>
          <w:r>
            <w:rPr>{b_tag}{c_tag}<w:sz w:val="{font_size_half_pt}"/><w:szCs w:val="{font_size_half_pt}"/></w:rPr>
            <w:t>{placeholder}</w:t>
          </w:r>
        </w:p>
      </w:sdtContent>
    </w:sdt>"""


def author_word_docx(docx_path: str, custom_title: str = None) -> None:
    if not os.path.exists(docx_path):
        raise FileNotFoundError(f"Layout file not found: {docx_path}. Run the AL build first.")

    with zipfile.ZipFile(docx_path, 'r') as zin:
        namelist = zin.namelist()
        item_xml_path = None
        item_props_path = None
        for name in namelist:
            if re.match(r'customXml/item\d+\.xml$', name):
                raw = zin.read(name).decode('utf-8', errors='replace')
                if 'ReportDataSet' in raw:
                    item_xml_path = name
                    idx = re.findall(r'\d+', name)[0]
                    cand_props = f'customXml/itemProps{idx}.xml'
                    if cand_props in namelist:
                        item_props_path = cand_props
                    break

        if not item_xml_path:
            raise ValueError("No Business Central ReportDataSet found in customXml/. Ensure the .docx was generated by the AL compiler.")

        raw_item_xml = zin.read(item_xml_path).decode('utf-8', errors='replace')
        # Extract xmlns
        m_ns = re.search(r'xmlns="([^"]+)"', raw_item_xml)
        ns_uri = m_ns.group(1) if m_ns else "urn:microsoft-dynamics-nav/reports"

        store_id = "{00000000-0000-0000-0000-000000000000}"
        if item_props_path:
            raw_props = zin.read(item_props_path).decode('utf-8', errors='replace')
            m_id = re.search(r'itemID="([^"]+)"', raw_props)
            if m_id:
                store_id = m_id.group(1)

    # Parse dataset structure ignoring namespace prefixes for tree traversal
    clean_xml = re.sub(r'\sxmlns="[^"]+"', '', raw_item_xml, count=1)
    root = ET.fromstring(clean_xml)

    labels = {}
    labels_el = root.find('Labels')
    if labels_el is not None:
        for child in labels_el:
            labels[child.tag] = f"/ns0:ReportDataSet[1]/ns0:Labels[1]/ns0:{child.tag}[1]"

    dataitems_el = root.find('DataItems')
    parent_di = None
    child_di = None
    parent_fields = []
    child_fields = []

    if dataitems_el is not None and len(dataitems_el) > 0:
        parent_di = dataitems_el[0]
        for elem in parent_di:
            if len(elem) > 0:
                if child_di is None:
                    child_di = elem
                    for sub in child_di:
                        if len(sub) == 0:
                            child_fields.append(sub.tag)
            else:
                parent_fields.append(elem.tag)

    # If flat dataset (no nested child DataItem), treat parent_di as the repeating table row
    if child_di is None and parent_di is not None:
        repeating_di_name = parent_di.tag
        repeating_xpath = f"/ns0:ReportDataSet[1]/ns0:DataItems[1]/ns0:{parent_di.tag}[1]"
        table_columns = [f for f in parent_fields if not f.lower().startswith('company')]
        company_fields = [f for f in parent_fields if f.lower().startswith('company')]
        header_fields = []
        total_fields = []
    else:
        repeating_di_name = child_di.tag if child_di is not None else "Line"
        repeating_xpath = f"/ns0:ReportDataSet[1]/ns0:DataItems[1]/ns0:{parent_di.tag}[1]/ns0:{repeating_di_name}[1]"
        table_columns = child_fields
        company_fields = [f for f in parent_fields if f.lower().startswith('company')]
        total_fields = [f for f in parent_fields if f.lower().startswith('total')]
        header_fields = [f for f in parent_fields if f not in company_fields and f not in total_fields]

    parent_xpath_prefix = f"/ns0:ReportDataSet[1]/ns0:DataItems[1]/ns0:{parent_di.tag}[1]" if parent_di is not None else "/ns0:ReportDataSet[1]/ns0:DataItems[1]"

    # Build Title
    title_label_key = next((k for k in labels if 'title' in k.lower()), None)
    if title_label_key:
        title_block = make_sdt_text(title_label_key, labels[title_label_key], ns_uri, store_id, custom_title or humanize(title_label_key).upper(), bold=True, align='center', font_size_half_pt=32, color='1F4E79')
    else:
        title_text = custom_title or (humanize(parent_di.tag) + " Report" if parent_di is not None else "Business Central Report")
        title_block = f'<w:p><w:pPr><w:jc w:val="center"/></w:pPr><w:r><w:rPr><w:b/><w:color w:val="1F4E79"/><w:sz w:val="32"/></w:rPr><w:t>{title_text}</w:t></w:r></w:p>'

    # Company Info Block
    company_xml = ""
    for cf in company_fields:
        company_xml += make_sdt_text(cf, f"{parent_xpath_prefix}/ns0:{cf}[1]", ns_uri, store_id, f"[{humanize(cf)}]", bold=(cf.lower().endswith('name')), font_size_half_pt=18)

    # Header Metadata Block
    header_xml = ""
    for hf in header_fields:
        header_xml += make_sdt_text(hf, f"{parent_xpath_prefix}/ns0:{hf}[1]", ns_uri, store_id, f"{humanize(hf)}: [{hf}]", bold=False, font_size_half_pt=20)

    # Table Columns & Header Row
    if not table_columns:
        table_columns = ["Description"]

    header_cells_xml = ""
    detail_cells_xml = ""
    for col in table_columns:
        align = 'right' if is_numeric_name(col) else 'left'
        cap_key = f"{col}_Caption"
        if cap_key in labels:
            cell_content = make_sdt_text(cap_key, labels[cap_key], ns_uri, store_id, humanize(col), bold=True, align=align, font_size_half_pt=20, color='FFFFFF')
        else:
            jc = f'<w:jc w:val="{align}"/>' if align != 'left' else ''
            cell_content = f'<w:p><w:pPr>{jc}<w:spacing w:before="60" w:after="60"/></w:pPr><w:r><w:rPr><w:b/><w:color w:val="FFFFFF"/><w:sz w:val="20"/></w:rPr><w:t>{humanize(col)}</w:t></w:r></w:p>'

        header_cells_xml += f"""<w:tc>
          <w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="1F4E79"/></w:tcPr>
          {cell_content}
        </w:tc>"""

        col_xpath = f"{repeating_xpath}/ns0:{col}[1]"
        detail_cells_xml += f"""<w:tc>
          <w:tcPr/>
          {make_sdt_text(col, col_xpath, ns_uri, store_id, f"[{col}]", bold=False, align=align, font_size_half_pt=20)}
        </w:tc>"""

    # Optional Totals Row
    totals_row_xml = ""
    if total_fields and len(table_columns) >= 1:
        tf = total_fields[0]
        total_lbl_key = next((k for k in labels if 'total' in k.lower()), None)
        if total_lbl_key:
            total_label_cell = make_sdt_text(total_lbl_key, labels[total_lbl_key], ns_uri, store_id, "Total", bold=True, align='left', font_size_half_pt=20)
        else:
            total_label_cell = '<w:p><w:r><w:rPr><w:b/><w:sz w:val="20"/></w:rPr><w:t>Total</w:t></w:r></w:p>'

        span = max(1, len(table_columns) - 1)
        grid_span = f'<w:gridSpan w:val="{span}"/>' if span > 1 else ''
        total_val_cell = make_sdt_text(tf, f"{parent_xpath_prefix}/ns0:{tf}[1]", ns_uri, store_id, f"[{tf}]", bold=True, align='right', font_size_half_pt=20)

        if len(table_columns) == 1:
            totals_row_xml = f'<w:tr><w:tc><w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="EDEDED"/></w:tcPr>{total_val_cell}</w:tc></w:tr>'
        else:
            totals_row_xml = f"""<w:tr>
              <w:tc><w:tcPr>{grid_span}<w:shd w:val="clear" w:color="auto" w:fill="F2F2F2"/></w:tcPr>{total_label_cell}</w:tc>
              <w:tc><w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="F2F2F2"/></w:tcPr>{total_val_cell}</w:tc>
            </w:tr>"""

    # Wrap everything in the parent DataItem repeating section if parent_di exists
    document_xml = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"
            xmlns:w14="http://schemas.microsoft.com/office/word/2010/wordml"
            xmlns:w15="http://schemas.microsoft.com/office/word/2012/wordml">
  <w:body>
    {company_xml}
    {title_block}
    {header_xml}
    <w:p><w:pPr><w:spacing w:before="80" w:after="80"/></w:pPr></w:p>
    <w:tbl>
      <w:tblPr>
        <w:tblW w:w="5000" w:type="pct"/>
        <w:tblBorders>
          <w:top w:val="single" w:sz="6" w:space="0" w:color="BFBFBF"/>
          <w:left w:val="single" w:sz="6" w:space="0" w:color="BFBFBF"/>
          <w:bottom w:val="single" w:sz="6" w:space="0" w:color="BFBFBF"/>
          <w:right w:val="single" w:sz="6" w:space="0" w:color="BFBFBF"/>
          <w:insideH w:val="single" w:sz="4" w:space="0" w:color="D9D9D9"/>
          <w:insideV w:val="single" w:sz="4" w:space="0" w:color="D9D9D9"/>
        </w:tblBorders>
        <w:tblCellMar>
          <w:top w:w="80" w:type="dxa"/>
          <w:left w:w="120" w:type="dxa"/>
          <w:bottom w:w="80" w:type="dxa"/>
          <w:right w:w="120" w:type="dxa"/>
        </w:tblCellMar>
      </w:tblPr>
      <w:tr>
        <w:trPr><w:tblHeader/></w:trPr>
        {header_cells_xml}
      </w:tr>
      <w:sdt>
        <w:sdtPr>
          <w:alias w:val="{repeating_di_name}"/>
          <w:tag w:val="{repeating_di_name}"/>
          <w:dataBinding w:prefixMappings="xmlns:ns0='{ns_uri}'" w:xpath="{repeating_xpath}" w:storeItemID="{store_id}"/>
          <w15:repeatingSection/>
        </w:sdtPr>
        <w:sdtContent>
          <w:sdt>
            <w:sdtPr><w15:repeatingSectionItem/></w:sdtPr>
            <w:sdtContent>
              <w:tr>
                {detail_cells_xml}
              </w:tr>
            </w:sdtContent>
          </w:sdt>
        </w:sdtContent>
      </w:sdt>
      {totals_row_xml}
    </w:tbl>
    <w:p><w:pPr><w:spacing w:before="240" w:after="120"/></w:pPr></w:p>
    <w:sectPr>
      <w:pgSz w:w="11906" w:h="16838"/>
      <w:pgMar w:top="850" w:right="850" w:bottom="850" w:left="850" w:header="450" w:footer="450" w:gutter="0"/>
    </w:sectPr>
  </w:body>
</w:document>"""

    # Replace ONLY word/document.xml inside the .docx archive
    fd, tmp_path = tempfile.mkstemp(suffix='.docx')
    os.close(fd)
    try:
        with zipfile.ZipFile(docx_path, 'r') as zin, zipfile.ZipFile(tmp_path, 'w', zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                if item.filename == 'word/document.xml':
                    zout.writestr(item, document_xml.encode('utf-8'))
                else:
                    zout.writestr(item, zin.read(item.filename))
        shutil.move(tmp_path, docx_path)
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
    print(f"[SUCCESS] Authored Word layout '{docx_path}' with {len(table_columns)} table column(s) bound to '{repeating_xpath}'.")


def main():
    parser = argparse.ArgumentParser(description="Populate BC compiler-generated report layout (.docx)")
    parser.add_argument("--layout", required=True, help="Path to compiler-generated .docx layout file")
    parser.add_argument("--title", default=None, help="Optional override for report title")
    args = parser.parse_args()

    ext = os.path.splitext(args.layout)[1].lower()
    if ext == '.docx':
        author_word_docx(args.layout, args.title)
    else:
        raise ValueError(f"Unsupported extension '{ext}' for automated script. Use .docx or edit RDLC <ReportSections> directly.")


if __name__ == "__main__":
    main()
